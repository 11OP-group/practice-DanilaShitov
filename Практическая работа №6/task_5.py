"""Задача 5. Ход ферзя

Даны две различные клетки шахматной доски. Определить, может ли ферзь
попасть с первой клетки на вторую одним ходом.

Формат входных данных:
    Четыре числа от 1 до 8: x1 y1 x2 y2.

Формат выходных данных:
    «YES» или «NO».
"""

# Константы размера доски
MIN_COORD, MAX_COORD = 1, 8

print("Программа определяет, может ли ферзь попасть с одной клетки на другую!")

try:
    x1, y1, x2, y2 = map(int, input("Введите x1 y1 x2 y2 (1–8) через пробел: ").split())
except ValueError:
    print("Ошибка ввода: введите четыре целых числа через пробел.")
    exit()

# Проверка ввода на корректность
if not (MIN_COORD <= x1 <= MAX_COORD and MIN_COORD <= y1 <= MAX_COORD and
        MIN_COORD <= x2 <= MAX_COORD and MIN_COORD <= y2 <= MAX_COORD):
    print("Ошибка ввода: координаты должны быть от 1 до 8.")
    exit()

# Ферзь ходит по вертикали, горизонтали или диагонали.
# Проверяем каждый случай отдельным блоком.

# Вертикаль — одинаковый столбец
if x1 == x2:
    print("YES")
# Горизонталь — одинаковая строка
elif y1 == y2:
    print("YES")
# Диагональ — разности совпадают (в одну или в другую сторону)
elif x1 - x2 == y1 - y2:
    print("YES")
elif x1 - x2 == y2 - y1:
    print("YES")
# Ничего не совпало — ход невозможен
else:
    print("NO")
