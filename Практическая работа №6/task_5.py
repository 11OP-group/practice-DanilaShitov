"""Задача 5. Ход ферзя

Даны две различные клетки шахматной доски. Напишите программу, которая
определяет, может ли ферзь попасть с первой клетки на вторую одним ходом.

Формат входных данных:
    Четыре числа от 1 до 8 каждое: номер столбца и номер строки сначала
    для первой клетки, потом для второй клетки.

Формат выходных данных:
    «YES», если из первой клетки ходом ферзя можно попасть во вторую,
    или «NO» в противном случае.

Примечание: шахматный ферзь ходит по диагонали, горизонтали или вертикали.
"""

# Константы размера доски
MIN_COORD, MAX_COORD = 1, 8

print("Вас приветствует программа, которая определяет, может ли ферзь попасть с одной клетки на другую!")

try:
    x1, y1, x2, y2 = map(int, input("Введите x1 y1 x2 y2 (1–8) через пробел: ").split())
except ValueError:
    print("Ошибка ввода: введите четыре целых числа через пробел.")
    exit()

# Проверка ввода на корректность
if not (MIN_COORD <= x1 <= MAX_COORD and MIN_COORD <= y1 <= MAX_COORD and
        MIN_COORD <= x2 <= MAX_COORD and MIN_COORD <= y2 <= MAX_COORD):
    print("Ошибка ввода: координаты должны быть от 1 до 8.")
    exit()

# Клетки должны быть различны
if x1 == x2 and y1 == y2:
    print("Ошибка: клетки должны быть различны.")
    exit()

# Ферзь ходит по вертикали, горизонтали или диагонали
# Используем цепочку логических условий через or
if x1 == x2 or y1 == y2 or abs(x1 - x2) == abs(y1 - y2):
    print(f"Ферзь может попасть из ({x1};{y1}) в ({x2};{y2}) одним ходом: YES")
else:
    print(f"Ферзь не может попасть из ({x1};{y1}) в ({x2};{y2}) одним ходом: NO")