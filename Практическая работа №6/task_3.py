print("Вас приветствует программа, которая определяет, одного ли цвета две клетки шахматной доски!")

try:
    x1, y1, x2, y2 = map(int, input("Введите x1 y1 x2 y2 (1–8) через пробел: ").split())
except ValueError:
    print("Ошибка ввода: введите четыре целых числа через пробел.")
    exit()

# Проверка ввода на корректность
if not (1 <= x1 <= 8 and 1 <= y1 <= 8 and 1 <= x2 <= 8 and 1 <= y2 <= 8):
    print("Ошибка ввода: координаты должны быть от 1 до 8.")
    exit()

# Клетка одного цвета, если сумма координат имеет одинаковую чётность.
# Сравниваем остатки от деления на 2 — это и есть «цвет» клетки.
if (x1 + y1) % 2 == (x2 + y2) % 2:
    color_status = "YES"
else:
    color_status = "NO"

print(f"Клетки ({x1};{y1}) и ({x2};{y2}) — {color_status}")