"""Задача 4. Ход слона

Даны две различные клетки шахматной доски. Определить, может ли слон
попасть с первой клетки на вторую одним ходом.

Формат входных данных:
    Четыре числа от 1 до 8: x1 y1 x2 y2.

Формат выходных данных:
    «YES» или «NO».
"""

# Константы размера доски
MIN_COORD, MAX_COORD = 1, 8

print("Программа определяет, может ли слон попасть с одной клетки на другую!")

try:
    x1, y1, x2, y2 = map(int, input("Введите x1 y1 x2 y2 (1–8) через пробел: ").split())
except ValueError:
    print("Ошибка ввода: введите четыре целых числа через пробел.")
    exit()

# Проверка ввода на корректность
if not (MIN_COORD <= x1 <= MAX_COORD and MIN_COORD <= y1 <= MAX_COORD and
        MIN_COORD <= x2 <= MAX_COORD and MIN_COORD <= y2 <= MAX_COORD):
    print("Ошибка ввода: координаты должны быть от 1 до 8.")
    exit()

# Слон ходит по диагонали:
# либо разность по столбцам равна разности по строкам,
# либо разность по столбцам равна обратной разности по строкам.
if x1 - x2 == y1 - y2:
    print("YES")
elif x1 - x2 == y2 - y1:
    print("YES")
else:
    print("NO")
